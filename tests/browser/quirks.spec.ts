import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { legacyCursedRun } from '../fixtures/legacy-content';

const drawbacks = ['Kleptomaniac', 'Curious', 'Compulsive Eater', 'Afraid of the Dark'];
for (const width of [1280, 390]) test(`DD quirks persist, respect slots and export in new games at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  await page.goto('/');
  await page.getByLabel('Names, one per line', { exact: true }).fill('Rowan\nCleo\nAsh\nFern');
  await page.getByRole('button', { name: 'Add to cast', exact: true }).click();
  await page.locator('.cast-person').first().click();
  let dialog = page.getByRole('dialog');
  await dialog.getByRole('checkbox', { name: 'Early Riser', exact: true }).check();
  await dialog.getByRole('checkbox', { name: 'Night Owl', exact: true }).check();
  for (const name of ['On Guard', 'Forest-wise']) await expect(dialog.getByRole('checkbox', { name, exact: true })).toBeDisabled();
  for (const name of drawbacks) await dialog.getByRole('checkbox', { name, exact: true }).check();
  await expect(dialog.getByRole('status', { name: 'Positive trait count' })).toHaveText('2 / 2');
  await expect(dialog.locator('.trait-descriptions')).toContainText('held oil lantern');
  await expect(dialog.locator('.trait-descriptions')).toContainText('Loyal still protects');
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await dialog.getByRole('button', { name: 'Done', exact: true }).click();
  await expect(page.getByText('Draft saved', { exact: true })).toBeVisible();
  await page.reload();
  await page.locator('.cast-person').first().click();
  dialog = page.getByRole('dialog');
  for (const name of ['Early Riser', 'Night Owl', ...drawbacks]) await expect(dialog.getByRole('checkbox', { name, exact: true })).toBeChecked();
  await dialog.getByRole('checkbox', { name: 'Night Owl', exact: true }).uncheck();
  await dialog.getByRole('checkbox', { name: 'On Guard', exact: true }).check();
  await dialog.getByRole('checkbox', { name: 'Early Riser', exact: true }).uncheck();
  await dialog.getByRole('checkbox', { name: 'Forest-wise', exact: true }).check();
  await dialog.getByRole('button', { name: 'Done', exact: true }).click();
  const exported = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export cast', exact: true }).click();
  const cast = JSON.parse(await readFile((await (await exported).path())!, 'utf8'));
  expect(cast.cast.players[0].traits).toEqual(expect.arrayContaining(['on-guard', 'forest-wise', 'kleptomaniac', 'curious', 'compulsive-eater', 'afraid-of-dark']));
  await page.locator('input[type=file]').first().setInputFiles({ name: 'quirk-cast.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(cast)) });
  await page.getByRole('button', { name: 'Game settings' }).click();
  await page.getByRole('button', { name: 'Start game' }).click();
  await expect(page.locator('.broadcast')).toHaveAttribute('data-revealed', '0');
  const replay = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export full replay', exact: true }).click();
  const saved = JSON.parse(await readFile((await (await replay).path())!, 'utf8'));
  expect(saved.run.engineVersion).toBe('1.28.0');
  expect(saved.run.input.cast.players[0].traits).toEqual(cast.cast.players[0].traits);
  expect(saved.run.input.content.items.some((item: { curse?: string }) => item.curse)).toBe(false);
  expect(JSON.stringify(saved.run.input.content)).not.toMatch(/crooked-compass|whispering-tin|dinner-bell/);
});

test('imports, displays and reloads the recorded cursed story from engine 1.15', async ({ page }) => {
  await page.goto('/');
  await page.locator('input[type=file]').first().setInputFiles({ name: 'legacy.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ kind: 'run', schemaVersion: 1, run: legacyCursedRun, cursor: 4 })) });
  await expect(page.locator('.broadcast')).toHaveAttribute('data-revealed', '4');
  await expect(page.locator('.phase-report')).toContainText(legacyCursedRun.events[3].text);
  await expect(page.locator('footer').getByRole('status')).toContainText('Progress saved');
  await page.reload();
  await page.getByRole('button', { name: 'Resume game', exact: false }).click();
  await expect(page.locator('.broadcast')).toHaveAttribute('data-revealed', '4');
  await expect(page.locator('.phase-report')).toContainText(legacyCursedRun.events[3].text);
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export full replay', exact: true }).click();
  const saved = JSON.parse(await readFile((await (await pending).path())!, 'utf8'));
  expect(saved.run).toEqual(legacyCursedRun);
});
